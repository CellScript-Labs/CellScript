pub(super) fn return_abi(name: &str) -> Option<RuntimeReturnAbi> {
    SURFACE
        .iter()
        .find(|entry| entry.0 == name)
        .map(|entry| entry.2)
        .or_else(|| ADDITIONAL.iter().find(|entry| entry.0 == name).map(|entry| entry.1))
}
